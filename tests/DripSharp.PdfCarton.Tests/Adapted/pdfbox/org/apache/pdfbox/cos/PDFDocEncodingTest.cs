  }

  internal virtual void testPDFBox3864() {
    for (int i = 0; (i < 256); i++) {
      string hex
        = global::DripSharp.Runtime.JavaCompat.JavaStringFormat(global::DripSharp.PdfCarton.Tests.Support.TestPath("pdfbox",
        "FEFF%04X"), i);
      global::DripSharp.PdfCarton.Cos.COSString cs1
        = global::DripSharp.PdfCarton.Cos.COSString.ParseHex(global::DripSharp.PdfCarton.Tests.Support.TestPath("pdfbox",
        hex));
      global::DripSharp.PdfCarton.Cos.COSString cs2
        = new global::DripSharp.PdfCarton.Cos.COSString(global::DripSharp.PdfCarton.Tests.Support.TestPath("pdfbox",
        cs1.GetString()));
      global::DripSharp.Testing.JavaAssertions.Equal(cs1, cs2, null);
    }
  }

